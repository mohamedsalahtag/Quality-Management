-- ============================================================================
--  SharbatlyQMS on Sharbatly_MIS  -  M10  -  Code descriptions
-- ============================================================================
--  Friendly names for the raw SAP codes the UI used to print bare:
--     Plant            JD01 -> Jeddah
--     StorageLocation  (JD01) JDCS -> JD Main Coldstor
--     PoType           ZFAS -> Air Shipment
--
--  Storage-location codes repeat across plants, so parent_code carries the
--  owning plant. Plant and PoType rows leave it NULL; parent_key is the
--  persisted ISNULL() of it purely so the uniqueness constraint works.
--
--  This replaces the hard-coded Models/SapPlantDirectory.cs lookup. That file
--  stays in the binary as SapPlantDirectorySeed and remains the fallback when
--  a code has no row here, so the list pages keep rendering names during the
--  window between a binary deploy and this migration.
--
--  The Plant + StorageLocation seed below is GENERATED from that C# file
--  (scratchpad/gen-code-desc-seed.ps1) -- do not hand-edit rows; regenerate.
--  PoType has no SAP master table anywhere, so it is seeded from whatever
--  codes the container cache has actually seen, with description = code. That
--  gives the admin a worklist to type real names into, not a blank page.
--
--  Managed from Parameters > Code Descriptions (Manager/SiteAdmin).
--  Idempotent: safe to re-run.
-- ============================================================================

IF OBJECT_ID('qms.qms_code_description') IS NULL
BEGIN
    CREATE TABLE qms.qms_code_description (
        code_desc_id  INT IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_qms_code_description PRIMARY KEY,
        domain        VARCHAR(20)  NOT NULL,
        parent_code   VARCHAR(4)   NULL,
        parent_key    AS ISNULL(parent_code, '') PERSISTED,
        code          VARCHAR(10)  NOT NULL,
        description   NVARCHAR(80) NOT NULL,
        sort_order    INT          NOT NULL
            CONSTRAINT DF_qms_code_description_sort DEFAULT 500,
        is_active     BIT          NOT NULL
            CONSTRAINT DF_qms_code_description_active DEFAULT 1,
        updated_at    DATETIME2    NOT NULL
            CONSTRAINT DF_qms_code_description_upd DEFAULT SYSUTCDATETIME(),
        updated_by    NVARCHAR(100) NULL,
        CONSTRAINT CK_qms_code_description_domain
            CHECK (domain IN ('Plant','StorageLocation','PoType')),
        CONSTRAINT UQ_qms_code_description
            UNIQUE (domain, parent_key, code)
    );
END
GO

-- The app addresses the table by its bare name; mirror the M05 convention.
IF OBJECT_ID('dbo.qms_code_description') IS NULL
    CREATE SYNONYM dbo.qms_code_description FOR qms.qms_code_description;
GO

