-- ---- Seed: PO types actually seen in the container cache ----
-- No SAP master exists for EKKO.BSART texts, so description starts as the
-- code itself; an admin renames them in Parameters > Code Descriptions.
INSERT INTO qms.qms_code_description (domain, parent_code, code, description, updated_by)
SELECT DISTINCT 'PoType', NULL, c.po_type, c.po_type, 'seed-M10'
FROM   qms.qms_sap_container_cache c
WHERE  c.po_type IS NOT NULL
  AND  c.po_type <> ''
  AND  NOT EXISTS (SELECT 1 FROM qms.qms_code_description d
                   WHERE d.domain = 'PoType' AND d.code = c.po_type);
GO

-- The three codes the cache actually holds, named from what the business calls
-- them. Only applied where the description is still the placeholder code, so an
-- admin's own wording is never overwritten by a re-run.
UPDATE qms.qms_code_description
SET    description = v.name, updated_by = 'seed-M10'
FROM   qms.qms_code_description d
JOIN   (VALUES ('ZFAS', N'Air Shipment'),
               ('ZFCO', N'Consignment'),
               ('ZFFP', N'Firm')) AS v(code, name) ON v.code = d.code
WHERE  d.domain = 'PoType' AND d.description = d.code;
GO

